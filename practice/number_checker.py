# Number Checker Program

num = int(input("Enter a number: "))

if num % 2 == 0:
    print("It is an Even number")
else:
    print("It is an Odd number")

if num > 0:

    print("It is Positive")

elif num < 0:

    print("It is Negative")
else:

    print("It is Zero")

